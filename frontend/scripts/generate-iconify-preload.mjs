function buildCollection(prefix, source, iconNames) {
  const icons = {};

  for (const iconName of iconNames) {
    const iconData = source.icons[iconName];
    if (!iconData) {
      throw new Error(`Missing icon "${prefix}:${iconName}" in installed collection.`);
    }
    icons[iconName] = iconData;
  }

  return {
    prefix,
    icons,
    width: source.width,
    height: source.height,
  };
}

const payload = Object.entries(requiredIcons).map(([prefix, iconNames]) =>
  buildCollection(prefix, collections[prefix], [...new Set(iconNames)].sort())
);

const output = `window.IconifyPreload = ${JSON.stringify(payload)};\n`;
const scriptDir = dirname(fileURLToPath(import.meta.url));
const publicVendorDir = resolve(scriptDir, '../public/vendor');
const target = resolve(publicVendorDir, 'iconify-preload.js');

mkdirSync(publicVendorDir, { recursive: true });
writeFileSync(target, output, 'utf8');
